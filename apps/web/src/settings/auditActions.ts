/** What an audit event was about, in words: "task" for `work_item`. */
const TARGET_WORDS: Record<string, string> = {
  work_item: 'task',
  work_item_label: 'label',
  external_agent: 'agent',
  external_execution: 'run request',
  mcp_credential: 'API token',
  organization: 'workspace',
  workspace_membership: 'workspace member',
  project_membership: 'project member',
  agent_profile: 'agent profile',
  provider_account: 'account for runs',
  saved_view: 'saved view',
  task_template: 'task template',
  project_template: 'project template',
  recurring_task: 'recurring task',
  secret: 'key',
}

/** The kind of thing an event changed, in plain words. */
export function targetWords(kind: string) {
  return TARGET_WORDS[kind] ?? kind.replaceAll('_', ' ')
}

/** For a code there are no words for yet. */
export const OTHER_CHANGE = 'made another change'

/** "changed a setting", or null for a code there are no words for yet. */
export function actionPhrase(action: string): string | null {
  // Changes made over MCP (`work_item.mcp_created`) read the same as the ones made here.
  return PHRASES[action] ?? PHRASES[action.replace('.mcp_', '.')] ?? null
}

/** "Signed in": an action on its own, starting with a capital. "Other change" for a code with no words yet. */
export function actionSentence(action: string) {
  const phrase = actionPhrase(action)
  if (!phrase) return 'Other change'
  return phrase.charAt(0).toUpperCase() + phrase.slice(1)
}

/** The thing the action was about, from its metadata, such as a setting's key or a key's name. */
export function actionDetail(action: string, metadata: Record<string, unknown>): string | null {
  const pick = (...names: string[]) => {
    for (const name of names) {
      const value = metadata[name]
      if (typeof value === 'string' && value) return value
    }
    return null
  }
  if (action.startsWith('setting.')) return pick('key')
  if (action.startsWith('secret.')) return pick('name')
  if (action === 'workspace.renamed') return pick('name', 'newName')
  if (action.startsWith('workspace_membership.')) return pick('role', 'displayName')
  return pick('name', 'title', 'displayName')
}

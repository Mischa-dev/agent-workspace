use std::{env, fs, path::Path};

// sqlx::migrate!() embeds the migration files at compile time but does not
// notice a newly added file on its own, so a build could ship (or a test could
// check) a stale set. Rebuild whenever the migrations directory changes.
fn main() {
    println!("cargo:rerun-if-changed=migrations");
    // The release script sets this to the commit it builds, for /health/version.
    println!("cargo:rerun-if-env-changed=AGENT_WORKSPACE_BUILD_COMMIT");
    core_modules();
}

/// Lists `src/modules/core/*/mod.rs` into `$OUT_DIR/core_modules.rs`: one
/// `mod` per folder, `ALL` (in folder-name order; the registry orders them by
/// manifest) and `CORE_WORDS`, the 64-bit words a set of them needs.
fn core_modules() {
    println!("cargo:rerun-if-changed=src/modules/core");
    println!("cargo:rerun-if-changed=../../modules");
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".to_owned());
    let folder = Path::new(&manifest_dir).join("src/modules/core");
    let mut ids = fs::read_dir(&folder)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .filter(|entry| entry.path().join("mod.rs").is_file())
                .filter_map(|entry| entry.file_name().into_string().ok())
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    ids.sort();
    let mut out = String::from("// Generated by build.rs from src/modules/core/*/mod.rs.\n\n");
    for id in &ids {
        let path = folder.join(id).join("mod.rs");
        out.push_str(&format!(
            "#[path = {:?}]\npub mod {id};\n",
            path.display().to_string()
        ));
    }
    out.push_str("\n/// Every core module's registration.\n");
    out.push_str("pub static ALL: &[&'static dyn crate::modules::registry::CoreModule] = &[\n");
    for id in &ids {
        out.push_str(&format!("    &{id}::MODULE,\n"));
    }
    out.push_str("];\n\n/// The 64-bit words a set of core modules needs.\n");
    out.push_str(&format!(
        "pub const CORE_WORDS: usize = {};\n",
        ids.len().div_ceil(64).max(1)
    ));
    let target =
        Path::new(&env::var("OUT_DIR").unwrap_or_else(|_| ".".to_owned())).join("core_modules.rs");
    if fs::read_to_string(&target).ok().as_deref() != Some(out.as_str()) {
        fs::write(&target, out).unwrap_or_else(|error| panic!("write core_modules.rs: {error}"));
    }
}
